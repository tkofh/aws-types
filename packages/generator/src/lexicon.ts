const upperFirst = (str: string): string =>
  str.charAt(0).toUpperCase() + str.slice(1)
const lowerFirst = (str: string): string =>
  str.charAt(0).toLowerCase() + str.slice(1)

function applyOperation(
  input: string,
  dictionary: ReadonlyArray<string>,
  mode: 'camel' | 'pascal',
): string {
  const result: Array<string> = []

  let name = input
    .toLowerCase()
    .split(/[-\s]/)
    .flatMap((part) => split(part))
    .join('')

  while (name.length > 0) {
    let found = false
    for (const part of dictionary) {
      if (name.endsWith(part)) {
        found = true
        result.unshift(upperFirst(part))
        name = name.slice(0, -part.length)
        break
      }
    }

    if (!found) {
      console.warn(`unknown prefix ${name} (from ${input})`)
      result.push(name)
      break
    }
  }

  return (
    mode === 'camel'
      ? [lowerFirst(result[0] as string), ...result.slice(1)]
      : result
  ).join('')
}

export function camelCaseResource(name: string): string {
  return applyOperation(name, resourceNameParts, 'camel')
}

export function pascalCaseResource(name: string): string {
  return applyOperation(name, resourceNameParts, 'pascal')
}

export function camelCaseArnParameter(name: string): string {
  return applyOperation(name, resourceArnParameterParts, 'camel')
}

export function pascalCaseArnParameter(name: string): string {
  return applyOperation(name, resourceArnParameterParts, 'pascal')
}
